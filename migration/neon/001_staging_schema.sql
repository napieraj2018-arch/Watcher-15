CREATE FUNCTION aib_stage_archive_profile_on_change() RETURNS trigger LANGUAGE plpgsql AS $body$
BEGIN
 IF OLD.encrypted_state IS DISTINCT FROM NEW.encrypted_state THEN
  INSERT INTO browser_profile_versions(profile_name,encrypted_state,source_updated_at,reason)
  VALUES(OLD.profile_name,OLD.encrypted_state,OLD.updated_at,'update');
 END IF;
 RETURN NEW;
END;
$body$;
CREATE TRIGGER aib_stage_archive_profile_before_update
 BEFORE UPDATE OF encrypted_state ON browser_profiles FOR EACH ROW
 EXECUTE FUNCTION aib_stage_archive_profile_on_change();
