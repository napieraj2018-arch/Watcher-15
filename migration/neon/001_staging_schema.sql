);
CREATE INDEX browser_profile_versions_profile_idx ON browser_profile_versions(profile_name,archived_at DESC,id DESC);
CREATE UNIQUE INDEX browser_profile_versions_protected_unique_idx ON browser_profile_versions(profile_name,reason,source_updated_at) WHERE reason <> 'update';
